#!/usr/bin/env bash
# ==============================================================================
# РЎРєСЂРёРїС‚ СЃР±РѕСЂРєРё Рё СЃРёРЅС‚Р°РєСЃРёС‡РµСЃРєРѕРіРѕ РєРѕРЅС‚СЂРѕР»СЏ РєРѕРЅС„РёРіСѓСЂР°С†РёР№ Рё СЂР°СЃС€РёСЂРµРЅРёР№ 1РЎ РЅР° Linux
# Р’РµСЂСЃРёСЏ 4.0 - РџСЂРѕРјС‹С€Р»РµРЅРЅС‹Р№ СЃС‚Р°РЅРґР°СЂС‚ СЃРѕ РІСЃРµРјРё 5 СЂСѓР±РµР¶Р°РјРё Р·Р°С‰РёС‚С‹
# ==============================================================================

set -euo pipefail

PATH_1C="/opt/1cv8/x86_64/current/1cv8"
DB_CONNECTION=""
DB_USER="Admin"
DB_PASS=""
EXT_NAME=""
TIMEOUT_LIMIT=300
SRC_DIR=""

RUN_ID=$(date +%Y%m%d_%H%M%S)_$RANDOM
LOG_FILE="/tmp/1c_log_${RUN_ID}.txt"
ERR_FILE="/tmp/1c_err_${RUN_ID}.txt"

# POSIX-РїР°С‚С‚РµСЂРЅ РѕС€РёР±РѕРє РєРѕРјРїРёР»СЏС†РёРё РІРѕ РІСЃРµС… СЏР·С‹РєРѕРІС‹С… Р»РѕРєР°Р»СЏС… РћРЎ
ERR_PATTERN="РѕС€РёР±РєР°\|РЅРµРѕРїРѕР·РЅР°РЅ\|РѕР¶РёРґР°РµС‚СЃСЏ\|РЅРµ РѕРїСЂРµРґРµР»РµРЅ\|РЅРµСЃРѕРѕС‚РІРµС‚СЃС‚РІ\|РЅРµ РЅР°Р№РґРµРЅ\|РЅРµРІРµСЂРЅ\|error\|expected\|undefined\|mismatch\|not found\|invalid\|failed"

usage() {
    echo "РСЃРїРѕР»СЊР·РѕРІР°РЅРёРµ: $0 [РѕРїС†РёРё]"
    echo "  -c CONNECT_STR  РЎС‚СЂРѕРєР° РїРѕРґРєР»СЋС‡РµРЅРёСЏ Рє Р±Р°Р·Рµ 1РЎ"
    echo "  -e EXT_NAME     РРјСЏ СЂР°СЃС€РёСЂРµРЅРёСЏ (РµСЃР»Рё СЃРѕР±РёСЂР°РµРј СЂР°СЃС€РёСЂРµРЅРёРµ)"
    echo "  -u USER         РРјСЏ Р°РґРјРёРЅРёСЃС‚СЂР°С‚РѕСЂР° РР‘"
    echo "  -w PASSWORD     РџР°СЂРѕР»СЊ Р°РґРјРёРЅРёСЃС‚СЂР°С‚РѕСЂР° РР‘"
    echo "  -s SRC_DIR      РљР°С‚Р°Р»РѕРі РёСЃС…РѕРґРЅС‹С… РєРѕРґРѕРІ РґР»СЏ Diff-РєРѕРЅС‚СЂРѕР»СЏ (Р СѓР±РµР¶ 5)"
    exit 1
}

# РџР°СЂСЃРёРЅРі Р°СЂРіСѓРјРµРЅС‚РѕРІ
while getopts "c:e:u:w:s:h" opt; do
    case "$opt" in
        c) DB_CONNECTION=$OPTARG ;;
        e) EXT_NAME=$OPTARG ;;
        u) DB_USER=$OPTARG ;;
        w) DB_PASS=$OPTARG ;;
        s) SRC_DIR=$OPTARG ;;
        h|*) usage ;;
    esac
done

if [[ -z "$DB_CONNECTION" ]]; then
    echo "[-] РћС€РёР±РєР°: РќРµ СѓРєР°Р·Р°РЅР° СЃС‚СЂРѕРєР° РїРѕРґРєР»СЋС‡РµРЅРёСЏ (-c)" >&2
    usage
fi

cleanup() {
    echo "[*] Р—Р°РїСѓСЃРє РїСЂРѕС†РµРґСѓСЂС‹ РѕС‡РёСЃС‚РєРё РґРµСЃРєСЂРёРїС‚РѕСЂРѕРІ Рё РІСЂРµРјРµРЅРЅС‹С… С„Р°Р№Р»РѕРІ..."
    rm -f "$LOG_FILE" "$ERR_FILE" "/tmp/diff_result_${RUN_ID}.txt" 2>/dev/null || true
}
trap cleanup EXIT

# Р СѓР±РµР¶ 4 (РїСЂРµРґРѕС‚РІСЂР°С‰РµРЅРёРµ РІР·Р°РёРјРЅС‹С… Р±Р»РѕРєРёСЂРѕРІРѕРє): Р·Р°С‡РёСЃС‚РєР° Р·Р°РІРёСЃС€РёС… .1cLck РїРµСЂРµРґ Р·Р°РїСѓСЃРєРѕРј
if [[ "$DB_CONNECTION" =~ ^/[Ff]"?([^";]+) ]] && ! pgrep -f "1cv8" >/dev/null; then
    BASE_PATH="${BASH_REMATCH[1]}"
    echo "[*] Р—Р°С‡РёСЃС‚РєР° Р·Р°РІРёСЃС€РёС… С„Р°Р№Р»РѕРІ Р±Р»РѕРєРёСЂРѕРІРѕРє РІ РєР°С‚Р°Р»РѕРіРµ ${BASE_PATH}..."
    rm -f "${BASE_PATH}"/*.1cLck "${BASE_PATH}"/1Cv8.lk 2>/dev/null || true
fi

# РџРѕРґРіРѕС‚РѕРІРєР° Р°СЂРіСѓРјРµРЅС‚РѕРІ Р·Р°РїСѓСЃРєР° РљРѕРЅС„РёРіСѓСЂР°С‚РѕСЂР° РґР»СЏ СЃРёРЅС‚Р°РєСЃРёС‡РµСЃРєРѕРіРѕ РєРѕРЅС‚СЂРѕР»СЏ
CMD_ARGS="DESIGNER $DB_CONNECTION /N "$DB_USER" /P "$DB_PASS" /CheckModules -Server -ThinClient -WebClient /Out "$LOG_FILE" -NoTruncate"
if [[ -n "$EXT_NAME" ]]; then
    CMD_ARGS="$CMD_ARGS -Extension "$EXT_NAME""
fi

echo "[*] Р—Р°РїСѓСЃРє СЏРґСЂР° РїР»Р°С‚С„РѕСЂРјС‹ 1РЎ (Р—Р°РїСѓСЃРє ID: ${RUN_ID})..."
set +e
timeout --preserve-status "$TIMEOUT_LIMIT" "$PATH_1C" $CMD_ARGS 2> "$ERR_FILE"
STATUS=$?
set -e

if [[ $STATUS -ne 0 ]]; then
    echo "[-] РљСЂРёС‚РёС‡РµСЃРєРёР№ СЃР±РѕР№ РїР»Р°С‚С„РѕСЂРјС‹ 1РЎ РёР»Рё РїСЂРµРІС‹С€РµРЅ С‚Р°Р№РјР°СѓС‚ РІС‹РїРѕР»РЅРµРЅРёСЏ (РљРѕРґ РІРѕР·РІСЂР°С‚Р°: $STATUS)" >&2
    if [[ -s "$ERR_FILE" ]]; then
        cat "$ERR_FILE" >&2
    fi
    exit "$STATUS"
fi

# Р СѓР±РµР¶ 2: РџСЂРѕРІРµСЂРєР° С„РёР·РёС‡РµСЃРєРѕРіРѕ РЅР°Р»РёС‡РёСЏ Рё РЅРµРЅСѓР»РµРІРѕРіРѕ СЂР°Р·РјРµСЂР° Р»РѕРіР°
if [[ ! -s "$LOG_FILE" ]]; then
    echo "[-] Р СѓР±РµР¶ 2 РїСЂРѕРІР°Р»РµРЅ: Р›РѕРі-С„Р°Р№Р» РїСѓСЃС‚ РёР»Рё РЅРµ СЃРѕР·РґР°РЅ. РЎР±РѕР№ СЏРґСЂР° РґРѕ СЃС‚Р°СЂС‚Р° РєРѕРјРїРёР»СЏС‚РѕСЂР°!" >&2
    if [[ -s "$ERR_FILE" ]]; then
        cat "$ERR_FILE" >&2
    fi
    exit 100
fi

# Р СѓР±РµР¶ 1: Р”РёРЅР°РјРёС‡РµСЃРєР°СЏ РЅРѕСЂРјР°Р»РёР·Р°С†РёСЏ РєРѕРґРёСЂРѕРІРѕРє Рё СѓРґР°Р»РµРЅРёРµ BOM-Р±Р°Р№С‚РѕРІ
MIME=$(file -b --mime-encoding "$LOG_FILE")
echo "[*] РћРїСЂРµРґРµР»РµРЅРёРµ РєРѕРґРёСЂРѕРІРєРё Р»РѕРіР°: ${MIME}"
if [[ "$MIME" != "utf-8" && "$MIME" != "us-ascii" ]]; then
    echo "[*] РљРѕРЅРІРµСЂС‚Р°С†РёСЏ Р»РѕРіР° РёР· ${MIME} РІ UTF-8..."
    iconv -f "$MIME" -t UTF-8 "$LOG_FILE" -o "${LOG_FILE}.tmp"
    mv -f "${LOG_FILE}.tmp" "$LOG_FILE"
fi
# РћС‡РёСЃС‚РєР° BOM
sed -i '1s/^ГЇВ»Вї//' "$LOG_FILE"

# Р СѓР±РµР¶ 3: РџРѕРёСЃРє РѕС€РёР±РѕРє СЃРёРЅС‚Р°РєСЃРёСЃР° РїРѕ РјСѓР»СЊС‚РёСЏР·С‹С‡РЅРѕРјСѓ С€Р°Р±Р»РѕРЅСѓ
if grep -Eiq "$ERR_PATTERN" "$LOG_FILE"; then
    echo "[-] Р СѓР±РµР¶ 3 РїСЂРѕРІР°Р»РµРЅ: РћР±РЅР°СЂСѓР¶РµРЅС‹ СЃРёРЅС‚Р°РєСЃРёС‡РµСЃРєРёРµ РѕС€РёР±РєРё РІ РјРѕРґСѓР»СЏС…!" >&2
    grep -EiaC 3 "$ERR_PATTERN" "$LOG_FILE" >&2
    exit 1
fi

# Р СѓР±РµР¶ 5: Diff-РІРµСЂРёС„РёРєР°С†РёСЏ С„Р°РєС‚Р° СЃРѕРѕС‚РІРµС‚СЃС‚РІРёСЏ РЎРЈР‘Р” РёСЃС…РѕРґРЅРѕРјСѓ РєРѕРґСѓ РІ Git
if [[ -n "$SRC_DIR" && -d "$SRC_DIR" ]]; then
    echo "[*] Р—Р°РїСѓСЃРє Р СѓР±РµР¶Р° 5: РІС‹РіСЂСѓР·РєР° РєРѕРЅС„РёРіСѓСЂР°С†РёРё РёР· Р±Р°Р·С‹ РґР»СЏ diff-СЃСЂР°РІРЅРµРЅРёСЏ..."
    TMP_DUMP="/tmp/dump_${RUN_ID}"
    mkdir -p "$TMP_DUMP"
    
    DUMP_ARGS="DESIGNER $DB_CONNECTION /N "$DB_USER" /P "$DB_PASS" /DumpConfigToFiles "$TMP_DUMP""
    if [[ -n "$EXT_NAME" ]]; then
        DUMP_ARGS="$DUMP_ARGS -Extension "$EXT_NAME""
    fi
    
    "$PATH_1C" $DUMP_ARGS >/dev/null
    
    set +e
    diff -r --strip-trailing-cr -x "ConfigDumpInfo.xml" -x "*.orig" "$SRC_DIR" "$TMP_DUMP" > /tmp/diff_result_${RUN_ID}.txt
    DIFF_STATUS=$?
    set -e
    
    rm -rf "$TMP_DUMP"
    
    if [[ $DIFF_STATUS -ne 0 ]]; then
        echo "[-] Р СѓР±РµР¶ 5 РїСЂРѕРІР°Р»РµРЅ: РљРѕРґ РІ РЎРЈР‘Р” РѕС‚Р»РёС‡Р°РµС‚СЃСЏ РѕС‚ РёСЃС…РѕРґРЅРѕРіРѕ РєРѕРґР° РІ РєРѕРјРјРёС‚Рµ!" >&2
        cat /tmp/diff_result_${RUN_ID}.txt >&2
        exit 2
    fi
    echo "[+] Р СѓР±РµР¶ 5 СѓСЃРїРµС€РЅРѕ РїСЂРѕР№РґРµРЅ: 100% РёРґРµРЅС‚РёС‡РЅРѕСЃС‚СЊ РєРѕРјРјРёС‚Р° Рё РЎРЈР‘Р” РїРѕРґС‚РІРµСЂР¶РґРµРЅР°."
fi

echo "[+] РЎР±РѕСЂРєР° Рё СЃРёРЅС‚Р°РєСЃРёС‡РµСЃРєРёР№ РєРѕРЅС‚СЂРѕР»СЊ СѓСЃРїРµС€РЅРѕ Р·Р°РІРµСЂС€РµРЅС‹ Р±РµР· Р·Р°РјРµС‡Р°РЅРёР№."
exit 0
